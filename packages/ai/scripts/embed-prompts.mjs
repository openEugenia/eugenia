#!/usr/bin/env node
// Embeds the prompts (prompts/*.md) in src/prompts/defaults.generated.ts, so that they can be
// used in the browser as well as in the CLI without file system access.
// Usage: node scripts/embed-prompts.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, "..", "prompts");
const target = join(here, "..", "src", "prompts", "defaults.generated.ts");

const names = readdirSync(promptsDir)
  .filter((f) => f.endsWith(".md") && f !== "README.md")
  .map((f) => f.slice(0, -3))
  .sort();

const entries = names.map((name) => {
  const text = readFileSync(join(promptsDir, `${name}.md`), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`;
});

const output = `// Generated by scripts/embed-prompts.mjs from prompts/*.md: do not edit.
export const DEFAULT_PROMPTS = {
${entries.join("\n")}
} as const;

export type PromptName = keyof typeof DEFAULT_PROMPTS;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing
  }
  if (current !== output) {
    console.error(
      "The embedded prompts are out of date: run `pnpm --filter @openeugenia/ai prompts`.",
    );
    process.exit(1);
  }
  console.log("Embedded prompts are up to date.");
} else {
  writeFileSync(target, output);
  console.log(`${names.length} prompts embedded in ${target}.`);
}
