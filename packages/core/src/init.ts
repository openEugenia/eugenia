/** Initialization of a new wiki: configuration, root, default categories (§8.1). */
import {
  CONFIG_PATH,
  DEFAULT_CONFIG,
  DEFAULT_MASTERY,
  serializeConfig,
  type WikiConfig,
} from "./config.ts";
import { serializePage } from "./pages.ts";
import { joinPath, normalizePath } from "./paths.ts";
import { folderNameFor } from "./slug.ts";
import { isoTimestamp } from "./time.ts";
import type { Visibility } from "./types.ts";
import { ulid } from "./ulid.ts";

/** Top-level categories offered by default (functional documentation §1). */
export const DEFAULT_CATEGORIES: readonly string[] = [
  "Arts and culture",
  "Economy and finance",
  "Geography",
  "History",
  "Languages and linguistics",
  "Medicine and health",
  "Military and defense",
  "Nature and environment",
  "Philosophy and thought",
  "Religion and beliefs",
  "Science",
  "Society and social sciences",
  "Sports and leisure",
  "Technology",
  "Transport",
];

export const PUBLISH_WORKFLOW_PATH = ".github/workflows/eugenia-publish.yml";
export const DEPLOY_KEY_SECRET = "EUGENIA_DEPLOY_KEY";
export const DEFAULT_ACTION_REF = "openEugenia/eugenia@v1";

export interface ScaffoldOptions {
  title: string;
  root?: string;
  library?: string;
  discussions?: string;
  categories?: readonly string[];
  defaultVisibility?: Visibility;
  privateRepo?: string;
  /** Target public repository: adds the publication workflow. */
  publicRepo?: string;
  actionRef?: string;
  branch?: string;
  now?: Date;
}

/** GitHub Actions workflow of the private repository: publication on every push (§6.4). */
export function publishWorkflow(
  publicRepo: string,
  options: { actionRef?: string; branch?: string } = {},
): string {
  const branch = options.branch ?? "main";
  return `# Publishes the public part of the wiki to ${publicRepo} on every push.
# Generated by Eugenia. Required secret: ${DEPLOY_KEY_SECRET} (deploy key with write access
# to ${publicRepo}), created by \`eugenia init --github\`.
name: Eugenia — publish

on:
  push:
    branches: [${branch}]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: eugenia-publish
  cancel-in-progress: true

jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v7
      - uses: ${options.actionRef ?? DEFAULT_ACTION_REF}
        with:
          target: ${publicRepo}
          deploy-key: \${{ secrets.${DEPLOY_KEY_SECRET} }}
`;
}

function readme(config: Pick<WikiConfig, "title" | "root" | "library" | "discussions">): string {
  return [
    `# ${config.title}`,
    "",
    "Personal knowledge wiki managed with [Eugenia](https://github.com/openEugenia/eugenia).",
    "",
    `- \`${config.root || "."}/\`: the wiki, from categories to atomic knowledge and its flashcards.`,
    `- \`${config.library}/\`: the library, the sources this knowledge comes from.`,
    `- \`${config.discussions}/\`: discussions with Eugenia, questions, quizzes and quick notes.`,
    "- Each page is a folder containing an `index.md`.",
    "- Files and folders starting with `_` or `.` are reserved for the application.",
    "- This repository must stay **private**: it also holds your private knowledge.",
    "",
    "Open it in the app: <https://openeugenia.github.io/eugenia/>.",
    "",
  ].join("\n");
}

const WELCOME = `Welcome to your personal wiki.

The wiki gathers your **atomic knowledge**, organized in categories, and the **flashcards**
you review it with. Each knowledge item points to the sources of your **library** it comes
from. The categories below are starting points: rename them, delete them or add your own.

Eugenia helps you extract knowledge from your sources, quick notes and discussions, describe
each sub-wiki and review with quizzes.`;

/** Files of a new wiki, ready to be committed. */
export function scaffoldWiki(options: ScaffoldOptions): Map<string, string> {
  const now = options.now ?? new Date();
  const root = normalizePath(options.root ?? "wiki");
  const visibility: Visibility = options.defaultVisibility ?? "private";
  const config: WikiConfig = {
    title: options.title,
    root,
    library: normalizePath(options.library ?? DEFAULT_CONFIG.library),
    discussions: normalizePath(options.discussions ?? DEFAULT_CONFIG.discussions),
    default_visibility: visibility,
    folder_name_max_length: 32,
    mastery: { ...DEFAULT_MASTERY },
    extra: {},
  };
  if (options.privateRepo) config.private_repo = options.privateRepo;

  const files = new Map<string, string>();
  files.set(CONFIG_PATH, serializeConfig(config));
  const stamp = isoTimestamp(now);
  let tick = now.getTime();
  files.set(
    joinPath(root, "index.md"),
    serializePage({
      fields: {
        id: ulid(tick++),
        type: "category",
        title: options.title,
        visibility,
        created: stamp,
        updated: stamp,
      },
      extra: {},
      body: WELCOME,
    }),
  );
  const taken = new Set<string>();
  for (const category of options.categories ?? DEFAULT_CATEGORIES) {
    const name = folderNameFor(category, taken, config.folder_name_max_length);
    taken.add(name);
    files.set(
      joinPath(root, name, "index.md"),
      serializePage({
        fields: {
          id: ulid(tick++),
          type: "category",
          title: category,
          visibility,
          created: stamp,
          updated: stamp,
        },
        extra: {},
        body: "",
      }),
    );
  }
  if (root !== "") files.set("README.md", readme(config));
  if (options.publicRepo) {
    const workflowOptions: { actionRef?: string; branch?: string } = {};
    if (options.actionRef) workflowOptions.actionRef = options.actionRef;
    if (options.branch) workflowOptions.branch = options.branch;
    files.set(PUBLISH_WORKFLOW_PATH, publishWorkflow(options.publicRepo, workflowOptions));
  }
  return files;
}
