/**
 * Index of a source (§8.6): a knowledge tree that describes the whole content of the source,
 * generated once by a model, then read at low cost — by going down from the root to the
 * relevant sections (tree search), or by comparing the meaning of a question with each section
 * (exhaustive search, with the embeddings of `_index/_embeddings.json`).
 *
 * The index is stored like the wiki: a folder per node, each with an `index.md`, in the
 * `_index/` folder of the source. The root (`_index/index.md`) sums up the source; the other
 * nodes are its **sections**, addressed by their folder path (`origins/lilitu`). Each node can
 * propose **knowledge to extract**: atomic statements with a first flashcard, ready for the
 * extraction (§8.1).
 *
 * ```
 * library/article-on-lilith/
 *   index.md                     the source
 *   _index/
 *     index.md                   root of the index (model, fingerprint of the text, summary)
 *     _embeddings.json           embeddings of the sections (never published)
 *     origins/
 *       index.md                 a section
 *       lilitu/index.md          a subsection
 * ```
 */
import { asNumber, asString, parseDocument, serializeDocument } from "./frontmatter.ts";
import type { WikiView } from "./operations.ts";
import { parsePage } from "./pages.ts";
import { dirname, isReservedName, joinPath } from "./paths.ts";
import { gitBlobSha } from "./sha.ts";
import { folderNameFor } from "./slug.ts";
import { isoTimestamp } from "./time.ts";
import { INDEX_EMBEDDINGS_FILE, SOURCE_INDEX_DIR, type WikiNode } from "./tree.ts";
import type { FileChange } from "./types.ts";

export const KNOWLEDGE_HEADING = "Knowledge to extract";

/** Knowledge proposed by the index: an atomic statement and its first flashcard. */
export interface KnowledgeCandidate {
  title: string;
  /** Self-contained statement; the bold part is the learning target. */
  statement: string;
  question: string;
  answer: string;
}

/** Node of a knowledge tree, as generated by the model. */
export interface KnowledgeNode {
  /** Title of the concept. */
  name: string;
  /** Self-contained explanation of the concept. */
  description: string;
  /** Knowledge worth extracting, proposed for this node. */
  knowledge?: KnowledgeCandidate[];
  children: KnowledgeNode[];
}

/** Node of a stored index. */
export interface SourceIndexNode {
  /** Folder path relative to `_index` (`""` for the root). */
  key: string;
  name: string;
  description: string;
  knowledge: KnowledgeCandidate[];
  children: SourceIndexNode[];
}

export interface SourceIndexDocument {
  /** Model that generated the index. */
  model: string;
  /** Fingerprint (git blob SHA, 7 characters) of the text of the source that was indexed. */
  textSha: string;
  generated: string;
  root: SourceIndexNode;
}

/** `missing`: no index; `stale`: the text of the source changed since; `invalid`: unreadable. */
export type SourceIndexStatus = "current" | "stale" | "missing" | "invalid";

/** Separator between the identifier of a source and the path of one of its sections. */
export const SECTION_SEPARATOR = "#";

export function sourceIndexDir(node: Pick<WikiNode, "path">): string {
  return joinPath(node.path, SOURCE_INDEX_DIR);
}

export function sourceIndexEmbeddingsPath(node: Pick<WikiNode, "path">): string {
  return joinPath(node.path, SOURCE_INDEX_DIR, INDEX_EMBEDDINGS_FILE);
}

/**
 * Text of a source sent to the model to index it: its title, authors and date, then its content
 * in Markdown (headings show the plan of the source, which the tree follows). The URL is left
 * out: it adds nothing to the content, and would invite the model to recall the page instead of
 * reading the text.
 */
export function sourceIndexText(indexContent: string): string {
  const doc = parsePage(indexContent);
  const f = doc.fields;
  const head = [`# ${f.title}`];
  if (f.authors?.length) head.push(`Authors: ${f.authors.join(", ")}`);
  if (f.published) head.push(`Published: ${f.published}`);
  return `${head.join("\n")}\n\n${doc.body.trim()}`.trim();
}

export async function sourceIndexTextSha(text: string): Promise<string> {
  return (await gitBlobSha(text)).slice(0, 7);
}

const oneLine = (text: unknown): string =>
  String(text ?? "")
    .replace(/\s+/g, " ")
    .trim();

function cleanCandidate(c: KnowledgeCandidate): KnowledgeCandidate | null {
  const candidate = {
    title: oneLine(c.title),
    statement: String(c.statement ?? "").trim(),
    question: oneLine(c.question),
    answer: oneLine(c.answer),
  };
  return candidate.statement ? { ...candidate, title: candidate.title || "Knowledge" } : null;
}

/**
 * Cleans a generated tree: trimmed texts, empty knowledge dropped, nodes without a name dropped
 * (their children move up).
 */
export function normalizeKnowledgeTree(node: KnowledgeNode): KnowledgeNode {
  const clean = (n: KnowledgeNode): KnowledgeNode[] => {
    const children = (Array.isArray(n.children) ? n.children : []).flatMap(clean);
    const name = oneLine(n.name);
    const description = String(n.description ?? "").trim();
    const knowledge = (Array.isArray(n.knowledge) ? n.knowledge : [])
      .map(cleanCandidate)
      .filter((c): c is KnowledgeCandidate => c !== null);
    if (!name) return children;
    return [{ name, description, knowledge, children }];
  };
  const [root] = clean(node);
  return root ?? { name: "", description: "", knowledge: [], children: [] };
}

// ---------------------------------------------------------------------------
// Pages of the index
// ---------------------------------------------------------------------------

function serializeKnowledge(knowledge: readonly KnowledgeCandidate[]): string {
  if (knowledge.length === 0) return "";
  const items = knowledge.map((k) =>
    [`### ${k.title}`, k.statement, "", `- Question: ${k.question}`, `- Answer: ${k.answer}`].join(
      "\n",
    ),
  );
  return `## ${KNOWLEDGE_HEADING}\n\n${items.join("\n\n")}`;
}

/** Description and knowledge to extract of the body of an index page. */
export function parseIndexBody(body: string): {
  description: string;
  knowledge: KnowledgeCandidate[];
} {
  const lines = body.split(/\r?\n/);
  const at = lines.findIndex((l) =>
    new RegExp(`^##\\s+${KNOWLEDGE_HEADING}\\s*$`, "i").test(l.trim()),
  );
  const description = (at < 0 ? lines : lines.slice(0, at)).join("\n").trim();
  const knowledge: KnowledgeCandidate[] = [];
  if (at >= 0) {
    let current: { title: string; lines: string[] } | null = null;
    const flush = (): void => {
      if (!current) return;
      const statement: string[] = [];
      let question = "";
      let answer = "";
      for (const line of current.lines) {
        const q = /^\s*[-*]\s*Question\s*:\s*(.*)$/i.exec(line);
        const a = /^\s*[-*]\s*(?:Expected answer|Answer)\s*:\s*(.*)$/i.exec(line);
        if (q) question = q[1]!.trim();
        else if (a) answer = a[1]!.trim();
        else statement.push(line);
      }
      const candidate = cleanCandidate({
        title: current.title,
        statement: statement.join("\n"),
        question,
        answer,
      });
      if (candidate) knowledge.push(candidate);
    };
    for (const line of lines.slice(at + 1)) {
      const heading = /^###\s+(.+?)\s*$/.exec(line);
      if (heading) {
        flush();
        current = { title: heading[1]!, lines: [] };
      } else if (current) {
        current.lines.push(line);
      }
    }
    flush();
  }
  return { description, knowledge };
}

function serializeIndexPage(
  fields: Record<string, unknown>,
  node: Pick<KnowledgeNode, "description" | "knowledge">,
): string {
  const body = [node.description.trim(), serializeKnowledge(node.knowledge ?? [])]
    .filter(Boolean)
    .join("\n\n");
  return serializeDocument(fields, body, [
    "type",
    "title",
    "order",
    "model",
    "text_sha",
    "generated",
  ]);
}

/**
 * Files of a new index (in the `_index/` folder of the source), replacing the previous one: its
 * pages that no longer exist are deleted. The embeddings are kept: their stale sections are
 * recomputed.
 */
export function sourceIndexChanges(
  view: Pick<WikiView, "files" | "config">,
  source: Pick<WikiNode, "path" | "title">,
  input: { model: string; textSha: string; root: KnowledgeNode; now?: Date },
): FileChange[] {
  const dir = sourceIndexDir(source);
  const root = normalizeKnowledgeTree(input.root);
  const written = new Map<string, string>();
  written.set(
    joinPath(dir, "index.md"),
    serializeIndexPage(
      {
        type: "source-index",
        title: root.name || source.title,
        model: input.model,
        text_sha: input.textSha,
        generated: isoTimestamp(input.now),
      },
      root,
    ),
  );
  const visit = (node: KnowledgeNode, folder: string): void => {
    const taken = new Set<string>();
    node.children.forEach((child, i) => {
      const name = folderNameFor(child.name, taken, view.config.folder_name_max_length);
      taken.add(name);
      const path = joinPath(folder, name);
      written.set(
        joinPath(path, "index.md"),
        serializeIndexPage({ type: "section", title: child.name, order: i + 1 }, child),
      );
      visit(child, path);
    });
  };
  visit(root, dir);
  const changes: FileChange[] = [...written].map(([path, content]) => ({
    op: "write",
    path,
    content,
  }));
  for (const path of view.files.keys()) {
    if (path.startsWith(`${dir}/`) && path.endsWith("/index.md") && !written.has(path)) {
      changes.push({ op: "delete", path });
    }
  }
  // The first format of the index (a JSON file next to the source) is replaced.
  for (const name of LEGACY_INDEX_FILES) {
    const path = joinPath(source.path, name);
    if (view.files.has(path)) changes.push({ op: "delete", path });
  }
  return changes;
}

/** Files of the first format of the index, deleted when the source is indexed again. */
export const LEGACY_INDEX_FILES: readonly string[] = ["_tree.json", "_tree.embeddings.json"];

/** Pages of the index of a source in a list of paths: `index.md` files of `_index/`. */
export function sourceIndexPages(
  paths: Iterable<string>,
  source: Pick<WikiNode, "path">,
): string[] {
  const dir = sourceIndexDir(source);
  const out: string[] = [];
  for (const path of paths) {
    if (!path.startsWith(`${dir}/`) || !path.endsWith("index.md")) continue;
    const rest = path.slice(dir.length + 1).split("/");
    if (rest.at(-1) === "index.md" && !rest.slice(0, -1).some(isReservedName)) out.push(path);
  }
  return out.sort();
}

/** Reads the index of a source, or `null` if it has none. Throws if its root is unreadable. */
export async function readSourceIndex(
  view: Pick<WikiView, "files" | "readText">,
  source: Pick<WikiNode, "path">,
): Promise<SourceIndexDocument | null> {
  const dir = sourceIndexDir(source);
  const rootPath = joinPath(dir, "index.md");
  if (!view.files.has(rootPath)) return null;
  const pages = sourceIndexPages(view.files.keys(), source);
  const texts = await Promise.all(pages.map((p) => view.readText(p)));
  const nodes = new Map<string, SourceIndexNode>();
  const orders = new Map<SourceIndexNode, number>();
  let meta: Record<string, unknown> = {};
  pages.forEach((path, i) => {
    const doc = parseDocument(texts[i]!);
    if (path === rootPath) {
      if (doc.error) throw new Error(doc.error);
      if (doc.data.type !== "source-index") throw new Error("Unknown index format.");
      meta = doc.data;
    }
    const key = dirname(path) === dir ? "" : dirname(path).slice(dir.length + 1);
    const { description, knowledge } = parseIndexBody(doc.body);
    const node: SourceIndexNode = {
      key,
      name: asString(doc.data.title)?.trim() || key.split("/").at(-1) || "",
      description,
      knowledge,
      children: [],
    };
    nodes.set(key, node);
    orders.set(node, asNumber(doc.data.order) ?? Number.POSITIVE_INFINITY);
  });
  // Each node under its parent folder (an intermediate folder without a page is skipped).
  for (const [key, node] of nodes) {
    if (key === "") continue;
    let parent = key;
    do parent = parent.includes("/") ? parent.slice(0, parent.lastIndexOf("/")) : "";
    while (parent !== "" && !nodes.has(parent));
    nodes.get(parent)!.children.push(node);
  }
  for (const node of nodes.values()) {
    node.children.sort((a, b) => orders.get(a)! - orders.get(b)! || a.name.localeCompare(b.name));
  }
  const textSha = asString(meta.text_sha);
  if (!textSha) throw new Error("Index without a text fingerprint.");
  return {
    model: asString(meta.model) ?? "",
    textSha,
    generated: asString(meta.generated) ?? "",
    root: nodes.get("")!,
  };
}

export function sourceIndexStatus(
  doc: Pick<SourceIndexDocument, "textSha"> | null | undefined,
  textSha: string,
): Exclude<SourceIndexStatus, "invalid"> {
  if (!doc) return "missing";
  return doc.textSha === textSha ? "current" : "stale";
}

/** Model, fingerprint and date of an index: its root page only. */
export type SourceIndexMeta = Omit<SourceIndexDocument, "root">;

/** Reads the root page of the index of a source, or `null` if it has none. */
export async function readSourceIndexMeta(
  view: Pick<WikiView, "files" | "readText">,
  source: Pick<WikiNode, "path">,
): Promise<SourceIndexMeta | null> {
  const rootPath = joinPath(sourceIndexDir(source), "index.md");
  if (!view.files.has(rootPath)) return null;
  const doc = parseDocument(await view.readText(rootPath));
  if (doc.error) throw new Error(doc.error);
  const textSha = asString(doc.data.text_sha);
  if (doc.data.type !== "source-index" || !textSha) throw new Error("Unknown index format.");
  return {
    model: asString(doc.data.model) ?? "",
    textSha,
    generated: asString(doc.data.generated) ?? "",
  };
}

export interface SourceIndexState {
  node: WikiNode;
  /** Text of the source to index. */
  text: string;
  textSha: string;
  status: SourceIndexStatus;
  /** Model, fingerprint and date of the current index, if readable. */
  meta?: SourceIndexMeta;
}

/**
 * State of the index of a source: current, stale (the source changed), missing or unreadable.
 * Only the root page of the index is read.
 */
export async function sourceIndexState(
  view: Pick<WikiView, "readText" | "files">,
  node: WikiNode,
): Promise<SourceIndexState> {
  const text = sourceIndexText(await view.readText(node.indexPath));
  const textSha = await sourceIndexTextSha(text);
  try {
    const meta = await readSourceIndexMeta(view, node);
    if (!meta) return { node, text, textSha, status: "missing" };
    return { node, text, textSha, status: sourceIndexStatus(meta, textSha), meta };
  } catch {
    return { node, text, textSha, status: "invalid" };
  }
}

