/** Section of the index of a source: a node below the root. */
export interface SourceSection {
  /** Folder path in the index: `origins/lilitu`. */
  key: string;
  /** Identifier of the section in the common hierarchy: `<source id>#<key>`. */
  id: string;
  name: string;
  description: string;
  knowledge: KnowledgeCandidate[];
  /** Names of the enclosing sections, from the top. */
  path: string[];
  childKeys: string[];
}

export function sectionId(sourceId: string, key: string): string {
  return `${sourceId}${SECTION_SEPARATOR}${key}`;
}

/** Source and key of a section identifier, or `null` for another identifier. */
export function parseSectionId(id: string): { sourceId: string; key: string } | null {
  const i = id.indexOf(SECTION_SEPARATOR);
  if (i <= 0) return null;
  const key = id.slice(i + 1);
  return /^[\p{L}\p{N}_-]+(\/[\p{L}\p{N}_-]+)*$/u.test(key)
    ? { sourceId: id.slice(0, i), key }
    : null;
}

/** Node of a key (`""` = the root). */
export function findIndexNode(root: SourceIndexNode, key: string): SourceIndexNode | undefined {
  if (key === "") return root;
  let node: SourceIndexNode | undefined = root;
  while (node && node.key !== key) {
    node = node.children.find((c) => key === c.key || key.startsWith(`${c.key}/`));
  }
  return node;
}

/** Nodes from the root to a section (both included), or `[]` if it does not exist. */
export function indexAncestry(root: SourceIndexNode, key: string): SourceIndexNode[] {
  const out: SourceIndexNode[] = [root];
  let node: SourceIndexNode | undefined = root;
  while (node && node.key !== key) {
    node = node.children.find((c) => key === c.key || key.startsWith(`${c.key}/`));
    if (node) out.push(node);
  }
  return node ? out : [];
}

/** All the sections of an index, depth-first (pre-order). */
export function sourceSections(sourceId: string, root: SourceIndexNode): SourceSection[] {
  const out: SourceSection[] = [];
  const visit = (node: SourceIndexNode, path: string[]): void => {
    for (const child of node.children) {
      out.push({
        key: child.key,
        id: sectionId(sourceId, child.key),
        name: child.name,
        description: child.description,
        knowledge: child.knowledge,
        path,
        childKeys: child.children.map((c) => c.key),
      });
      visit(child, [...path, child.name]);
    }
  };
  visit(root, []);
  return out;
}

/** Number of nodes of a tree, root included. */
export function countIndexNodes(root: {
  children: readonly { children: readonly unknown[] }[];
}): number {
  return (
    1 +
    root.children.reduce(
      (n, c) => n + countIndexNodes(c as { children: readonly { children: readonly unknown[] }[] }),
      0,
    )
  );
}

/** Knowledge proposed by a node and its descendants, with the section that proposes it. */
export function indexKnowledge(
  node: SourceIndexNode,
): { key: string; section: string; candidate: KnowledgeCandidate }[] {
  return [
    ...node.knowledge.map((candidate) => ({ key: node.key, section: node.name, candidate })),
    ...node.children.flatMap(indexKnowledge),
  ];
}

/** Text of a section for its embedding: where it is in the source, then its content. */
export function sectionEmbeddingText(sourceTitle: string, section: SourceSection): string {
  return [
    [sourceTitle, ...section.path, section.name].join(" › "),
    section.description,
    ...section.knowledge.map((k) => k.statement),
  ]
    .filter((p) => p.trim() !== "")
    .join("\n\n");
}
